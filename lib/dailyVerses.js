/**
 * The verse for a given date, by day of year (1 January → 0). 29 February
 * shares its verse with 28 February so the list stays at 365.
 */
function dailyVerse(date = new Date()) {
  const start = Date.UTC(date.getUTCFullYear(), 0, 1);
  const today = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  let dayOfYear = Math.floor((today - start) / 86400000);
  const isLeap = (y => (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0)(date.getUTCFullYear());
  if (isLeap && dayOfYear >= 59) dayOfYear -= 1;   // 59 = 29 February in a leap year
  const [book, chapter, verse] = DAILY_VERSES[dayOfYear % DAILY_VERSES.length];
  return { book, chapter, verse, dayOfYear };
}

