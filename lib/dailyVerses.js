// systems split or merge differently (9–10, 114–116, 147) are left out of
// this list so that conversion is always a plain shift.
//
// Taglines are not stored here. A one-line reflection is written by the
// model for the day's verse in the requested language and cached until
// midnight — six languages of hand-written captions for 365 verses was the
