//
// Book numbers are canonical order 1–66, matching BOOK_CODES in server.js.
// Psalm numbers are Masoretic (as in the English, Spanish, French, Portuguese
// and Tagalog texts). The Synodal Russian Psalter follows the Septuagint —
// one behind between Psalms 10 and 147, with superscriptions counted as
